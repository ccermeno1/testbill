class SplitLoader:
    """Read-only access to the frozen split.

    Checks integrity on load. Test stays sealed: `load("test")` requires
    allow_test=True and the experiment runner never passes it.
    """

    def __init__(
        self,
        splits_dir: str | Path,
        data_root: str | Path | None = None,
        *,
        version: str | None = None,
    ):
        """`splits_dir` is the container of versions; `version` picks one
        (`None` = the latest). `self.version` says which one was resolved, so
        a run can record it instead of the ambiguous "latest"."""
        self.splits_dir = resolve_version(splits_dir, version)
        self.version = self.splits_dir.name
        manifest_path = self.splits_dir / MANIFEST_NAME
        self.manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        self.data_root = Path(data_root or self.manifest["data_root"])
        self._assignment = {
            name: _read_split_file(self.splits_dir / f"{name}.txt")
            for name in SPLIT_NAMES
        }
        self._layout = detect_layout(self.data_root)
        self._by_id = {s.sample_id: s for s in self._layout.all_samples}
        self._verify()

    def _verify(self) -> None:
        _check_disjoint(self._assignment)
        strategy = GroupStrategy(self.manifest["group_strategy"])
        if strategy is not GroupStrategy.NONE:
            config = GroupConfig(
                strategy=strategy,
                regex=self.manifest.get("group_regex"),
                manifest_path=(
                    Path(self.manifest["group_manifest"])
                    if self.manifest.get("group_manifest")
                    else None
                ),
                independence_confirmed=True,
            )
            _check_groups_disjoint(
                self._assignment,
                self._layout,
                config.resolver(require_independence_confirmation=False),
            )

        listed = {sid for ids in self._assignment.values() for sid in ids}
        missing = sorted(listed - set(self._by_id))
        if missing:
            raise SplitError(
                f"{len(missing)} samples of the split are not in "
                f"{self.data_root}: {missing[:10]}"
                + (" ..." if len(missing) > 10 else "")
                + ". The split is frozen; if the data directory changed, fix "
                "the directory, not the split"
            )

    def unassigned(self) -> tuple[str, ...]:
        listed = {sid for ids in self._assignment.values() for sid in ids}
        return tuple(sorted(set(self._by_id) - listed))

    def load(self, split: str, *, allow_test: bool = False) -> tuple[Sample, ...]:
        if split not in SPLIT_NAMES:
            raise SplitError(f"unknown split '{split}'; valid: {SPLIT_NAMES}")
        if split == "test" and not allow_test:
            raise SealedTestSetError(
                "test is sealed. The experiment runner cannot read it: looking "
                "at test during development turns it into a second validation "
                "set. Use the `evaluate-test` command, which records every "
                "access in runs/test_evaluations.jsonl"
            )
        return tuple(self._by_id[sid] for sid in self._assignment[split])

    def ids(self, split: str) -> tuple[str, ...]:
        return tuple(self._assignment[split])

    def describe(self) -> dict:
        """What a run records about the split it used: enough to know whether
        two runs are comparable without opening the split files."""
        return {
            "version": self.version,
            "mode": self.manifest.get("mode"),
            "digest": self.manifest.get("digest"),
            "counts": dict(self.manifest.get("counts", {})),
        }


# -- the sealed test set ----------------------------------------------------


def read_test_accesses(log_path: Path | None = None) -> list[dict]:
    """Previous accesses to the sealed set, oldest to newest.

    Read BEFORE evaluating, and shown. The seal does not prevent looking at
    test: it prevents looking at it without a record. Seeing the count up
    front is what makes the record worth anything.
    """
    path = Path(log_path or TEST_LOG_PATH)
    if not path.exists():
        return []
    entries: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError:
            # A corrupt line cannot hide the others: the access count is
            # precisely what must not be losable.
            entries.append({"utc": "?", "run": "?", "reason": "[unreadable line]"})
    return entries


def record_test_access(
    reason: str,
    run_name: str,
    log_path: Path | None = None,
    **details,
) -> dict:
    """Record every access to the sealed set.

    `details` stores WHAT was evaluated -- commit, weights, metric obtained --
    not only when. A log that only says "someone looked at test on Tuesday"
    is useless for the only thing that matters: knowing whether the final
    number was picked among several.
    """
    path = Path(log_path or TEST_LOG_PATH)
    path.parent.mkdir(parents=True, exist_ok=True)
    entry = {"utc": _now(), "run": run_name, "reason": reason, **details}
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
    return entry
